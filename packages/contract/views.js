// Read-only tables for people who open the Google Sheet: Exhibits 1-3 as the centre knows them, plus today's
// lessons. Built from the fact tables with the same derive functions the portals use, then written to
// "View - ..." tabs by the Sheets backend. Pure functions; nothing reads these tabs back.
import * as derive from './derive.js';
import * as tt from './timetable.js';

export const VIEW_PREFIX = 'View - ';
const NOTE = 'Generated by the app from the fact tabs after every change. Edits here are overwritten.';
const OUTCOME = { DONE: 'DONE', W: 'W', C: 'C', BLANK: 'Blank' };
const OUTCOME_BG = { DONE: '#e7f6ec', W: '#fde8e8', C: '#fff4e0', BLANK: '#eef1f6' };
const STATUS = { mastered: 'Mastered', partial: 'Partial', 'not-understood': 'Not understood', 'not-covered': 'Not covered', insufficient: 'Not enough evidence' };
const STATUS_BG = { mastered: '#b7e4c7', partial: '#fde9b0', 'not-understood': '#f6c1bc', 'not-covered': '#eef1f6', insufficient: '#f3f6fb' };
const BAND_BG = { green: '#e7f6ec', amber: '#fff4e0', red: '#fde8e8' };
const ATT = { present: 'Present', late: 'Late', absent: 'Absent' };

// Every view: { title, rows: [[header...], ...], colors: same shape, null = no fill }
function view(name, header, body, bodyColors) {
  const rows = [header, ...body.map(r => r), [NOTE]];
  const colors = [header.map(() => '#dbeafe'), ...bodyColors, [null]];
  return { title: VIEW_PREFIX + name, rows, colors };
}

/** data: { students, modules, tests, policy, timetable, TODAY }; facts: { results, changes, attendance } */
export function buildViews(data, { results, changes = [], attendance = [] }) {
  const ref = derive.indexReference(data);
  const name = id => data.students.find(s => s.id === id)?.name || id;

  // Exhibit 1 - one row per student x test x attempt
  const maxQ = Math.max(...data.tests.map(t => t.questions.length));
  const qCols = Array.from({ length: maxQ }, (_, i) => `Q${i + 1}`);
  const sheet = derive.markingSheet(results, ref);
  const e1 = view('Exhibit 1 Marking', ['Student', 'Test', 'Attempt', 'Marked', ...qCols, 'Score', 'Total', '%'],
    sheet.map(r => [name(r.studentId), ref.testIndex[r.testId].name, r.attempt, r.markedAt.slice(0, 10),
      ...qCols.map((_, i) => OUTCOME[r.cells[i + 1]?.outcome] || ''), r.score, r.total, r.pct]),
    sheet.map(r => [null, null, null, null, ...qCols.map((_, i) => OUTCOME_BG[r.cells[i + 1]?.outcome] || null), null, null, BAND_BG[derive.band(r.pct, data.policy)]]));

  // Exhibit 2 - knowledge-point heat-map
  const kps = data.modules.flatMap(m => m.kps);
  const progress = data.students.map(s => derive.progressRow(results, s, data.modules, ref, data.policy));
  const e2 = view('Exhibit 2 Progress', ['Student', ...kps.map(k => `${k.id} ${k.name}`), 'Mastered %', 'Partial %', 'Not understood %'],
    progress.map(p => [name(p.studentId), ...kps.map(k => STATUS[p.cells[k.id].status] + (p.cells[k.id].cCount ? ` (C×${p.cells[k.id].cCount})` : '')),
      p.summary.mastered, p.summary.partial, p.summary.notUnderstood]),
    progress.map(p => [null, ...kps.map(k => STATUS_BG[p.cells[k.id].status]), null, null, null]));

  // Exhibit 3 - latest attempt per student x test
  const stats = derive.examStats(results, data.students, data.tests, data.policy);
  const e3 = view('Exhibit 3 Exam stats', ['Student', ...data.tests.map(t => t.name)],
    stats.map(s => [name(s.studentId), ...data.tests.map(t => { const x = s.tests[t.id]; return x ? `${x.pct}% (${x.score}/${x.total}, attempt ${x.latest})` : ''; })]),
    stats.map(s => [null, ...data.tests.map(t => (s.tests[t.id] ? BAND_BG[s.tests[t.id].band] : null))]));

  // Today's lessons with changes and attendance
  const lessons = tt.lessonsBetween(data.TODAY, data.TODAY, { template: data.timetable, changes, attendance });
  const state = o => (o.state === 'cancelled' ? 'Cancelled (leave)' : o.state === 'moved' ? `Moved to ${tt.label(o.movedTo.date)} ${o.movedTo.start}`
    : o.extra ? 'Extra lesson' : o.movedFrom ? `Moved from ${tt.label(o.movedFrom.date)}` : o.change?.kind === 'online' ? 'Switched online' : 'Scheduled');
  const tl = view(`Timetable ${data.TODAY}`, ['Time', 'Student', 'Teacher', 'Room', 'Mode', 'Status', 'Attendance'],
    lessons.map(o => [`${o.start}-${o.end}`, name(o.studentId), o.teacher, o.room, o.mode, state(o), ATT[o.attendance?.status] || '']),
    lessons.map(o => [null, null, null, null, null, o.state === 'scheduled' ? null : '#eef1f6',
      o.attendance ? { present: '#e7f6ec', late: '#fff4e0', absent: '#fde8e8' }[o.attendance.status] : null]));

  return [e1, e2, e3, tl];
}
